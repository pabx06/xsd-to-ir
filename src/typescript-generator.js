const { createHash } = require('node:crypto');
const { generateJSONSchema } = require('./json-schema-generator');
const { generateUIJSONSchema } = require('./ui-json-schema');
const { normalizeIR } = require('./ui-contract');
const { TypeScriptSchema } = require('./typescript-schema');

const registries = [
  ['entities', 'Entities', 'Entity'],
  ['valueTypes', 'ValueTypes', 'Value'],
  ['enums', 'Enums', 'Enum'],
  ['simpleTypes', 'SimpleTypes', 'Simple'],
];
const sorted = (map) => [...map.keys()].sort();
const identifier = (name) => name.split(/[^a-zA-Z0-9]+/).filter(Boolean)
  .map((part) => part[0].toUpperCase() + part.slice(1)).join('') || 'Unnamed';
const hash = (name) => createHash('sha256').update(name).digest('hex').slice(0, 12);

function comments(lines) {
  const text = lines.filter(Boolean).join('\n').replace(/\*\//g, '* /');
  return text ? `/**\n${text.split(/\r?\n/).map((line) => ` * ${line}`).join('\n')}\n */\n` : '';
}

function namesFor(ir) {
  const aliases = new Map();
  const reserved = new Set(registries.map(([, mapName]) => mapName));
  for (const [registry, , prefix] of registries) {
    const groups = new Map();
    for (const name of sorted(ir[registry])) {
      const candidate = prefix + identifier(name);
      if (!groups.has(candidate)) groups.set(candidate, []);
      groups.get(candidate).push(name);
    }
    const used = new Set([...groups.keys(), ...reserved]);
    const names = new Map();
    for (const [candidate, originals] of groups) {
      for (const name of originals) {
        let alias = candidate;
        if (originals.length > 1 || reserved.has(candidate)) {
          alias += `_${hash(name)}`;
          while (used.has(alias)) alias += '_';
          used.add(alias);
        }
        names.set(name, alias);
      }
    }
    aliases.set(registry, names);
  }
  return aliases;
}

/**
 * Generate a standalone TypeScript module for one IR / S3000L issue.
 * Accepts a live IR (Maps) or its serialized ir.json snapshot. Clean UI types
 * are the default; representation="xml" retains the decoded wire contract.
 * This function does not decode database rows or normalize values.
 */
function generateTypeScript(input, options = {}) {
  const representation = options.representation || 'ui';
  if (!['ui', 'xml'].includes(representation)) {
    throw new Error(`Unknown TypeScript representation: ${representation}`);
  }
  const ir = normalizeIR(input);
  const schema = representation === 'xml' ? generateJSONSchema(ir) : generateUIJSONSchema(ir);
  const aliases = namesFor(ir);
  const renderer = new TypeScriptSchema((reference) => {
    if (reference.startsWith('#/definitions/')) {
      const name = reference.slice('#/definitions/'.length).replace(/~1/g, '/').replace(/~0/g, '~');
      const alias = aliases.get('valueTypes').get(name);
      if (alias) return alias;
    } else if (reference.startsWith('#/$defs/')) {
      const name = reference.slice('#/$defs/'.length);
      // JSON Schema's shared $defs registry gives entities precedence over simple types and enums.
      for (const registry of ['entities', 'simpleTypes', 'enums']) {
        const alias = aliases.get(registry).get(name);
        if (alias) return alias;
      }
    }
    throw new Error(`Unresolved TypeScript reference: ${reference}`);
  });
  const output = [comments([
    'Generated by xsd-to-ir. Do not edit.',
    ir.s3000lDialect ? `S3000L issue ${ir.s3000lDialect}; select this module using the project's issue.` : null,
    representation === 'xml'
      ? 'Entity types match the generated JSON Schema; value types describe decoded XML-shaped JSON cells.'
      : 'Entity types match the generated UI JSON Schema; value types describe clean editable values.',
    'No database decoding, relation loading, data normalization, or runtime validation is performed.',
    'Use strict and exactOptionalPropertyTypes. Optional never properties express field absence.',
    representation === 'xml'
      ? 'Legacy singleton/array and scalar forms remain accepted, as in JSON Schema.'
      : 'Repeated fields are nonempty arrays when present; XML metadata is handled by the adapter.',
    'String/numeric facets, arbitrary XPath, XML ordering and bounds above 20 require runtime validation.',
    'TypeScript structural typing does not enforce closed objects on existing variables.',
  ])];

  for (const [registry, mapName] of registries) {
    const names = aliases.get(registry);
    for (const name of sorted(ir[registry])) {
      const definition = registry === 'valueTypes' ? schema.definitions[name] : schema.$defs[name];
      const documentation = comments([
        `${registry}: ${name}`,
        definition.description,
        ...(definition['x-xsd-assertions'] || []).map((rule) => `@xsdAssertion ${rule}`),
        ...(definition['x-xsd-unsupported'] || []).map((reason) => `@runtimeValidation ${reason}`),
      ]);
      output.push(`${documentation}export type ${names.get(name)} = ${renderer.type(definition)};\n`);
    }
    const documentation = comments([`Lookup by exact IR ${registry} key, including anonymous valueTypeRef paths.`]);
    const entries = sorted(ir[registry]).map((name) => `  ${JSON.stringify(name)}: ${names.get(name)};`);
    output.push(`${documentation}export interface ${mapName} {\n${entries.join('\n')}\n}\n`);
  }
  return `${output.join('\n')}\n`;
}

module.exports = { generateTypeScript };
